SELECT ESTAB.FANT_ESTB || '(' || COALESCE(ESTAB.CNPJCPF_ESTB, ' ') || ')' EMPRESA,
CASE WHEN DOC.MOV_DOC = 'S' THEN 'SAIDA' ELSE 'ENTRADA' END MOV,
'NF' TIPO, 
COALESCE(GRPIT.SPEDPISCOFINS_TRIB,'N') SPED,
'NF ' || COALESCE(DOC.NUM_DOC, ' ') NUM_NF,
DOC.NOM_PESS PESSOA,
DOCIT.CFOP_DOCIT||' ' CFOP,
DOC.EMISS_DOC EMISSAO,
DOC.ENTSAID_DOC ENTSAIDA,
PROD.COD_ESTAB||'-'||PROD.CODBAR_PROD COD_ITEM,
PROD.NOM_PROD PRODUTO,
DOCIT.QTDE_DOCIT QTDE, 
PROD.UNSD_PROD UN, 
DOC.CANC_DOC SIT,
CASE WHEN DOCIT.CFOP_DOCIT = 5929 THEN 0 ELSE DOCIT.TOTAL_DOCIT + COALESCE(DOCIT.VRDESC_DOCIT,0) END VL_ITEM,
CASE WHEN DOCIT.CFOP_DOCIT = 5929 THEN 0 ELSE COALESCE(DOCIT.VRDESC_DOCIT,0) END VL_DESC,
CASE WHEN DOCIT.CFOP_DOCIT = 5929 THEN 0 ELSE COALESCE(DOCIT.FRETE_DOCIT,0) END VL_FRETE,
CASE WHEN DOCIT.CFOP_DOCIT = 5929 THEN 0 ELSE COALESCE(DOCIT.SEGURO_DOCIT,0) END VL_SEGURO,
CASE WHEN DOCIT.CFOP_DOCIT = 5929 THEN 0 ELSE COALESCE(DOCIT.OUTDESP_DOCIT,0) END VL_OUTDESP,
CASE WHEN DOCIT.CFOP_DOCIT = 5929 THEN 0 ELSE DOCIT.TOTAL_DOCIT  + COALESCE(DOCIT.FRETE_DOCIT,0) + COALESCE(DOCIT.SEGURO_DOCIT,0) + COALESCE(DOCIT.OUTDESP_DOCIT,0) + COALESCE(DOCIT.ICMSR_DOCIT,0) END VL_GERAL,
CASE WHEN DOCIT.CFOP_DOCIT = 5929 THEN 0 ELSE DOCIT.MOVESTQ_DOCIT END ESTQ,
CASE WHEN DOCIT.CFOP_DOCIT = 5929 THEN 0 ELSE DOCIT.ICMS_DOCIT END ICMS,
CASE WHEN DOCIT.CFOP_DOCIT = 5929 THEN 0 ELSE DOCIT.ICMSR_DOCIT END ICMSR,
CASE WHEN DOCIT.CFOP_DOCIT = 5929 THEN 0 ELSE DOCIT.IPI_DOCIT END IPI,
GRPIT.CST_PIS|| ' ' CST_PIS,
GRPIT.CST_COFINS || ' ' CST_COFINS,
COALESCE(GRPIT.BC_PIS,'S') CALC_BC_PIS,
COALESCE(GRPIT.BC_COFINS,'S') CALC_BC_COFINS
FROM DOCIT
INNER JOIN DOC ON (DOC.COD_DOC = DOCIT.COD_DOC)
INNER JOIN ESTAB ON (ESTAB.COD_ESTAB = DOC.COD_ESTAB)
LEFT JOIN CFOP ON (CFOP.COD_CFOP = DOCIT.CFOP_DOCIT AND CFOP.INT_CFOP = DOCIT.INTCFOP_DOCIT)
LEFT JOIN PROD ON (PROD.COD_ESTQ = DOCIT.COD_ESTQ)
LEFT JOIN GRPIT ON (PROD.COD_GRP = GRPIT.COD_GRP AND ESTAB.COD_ESTAB = GRPIT.COD_ESTAB AND CFOP.CLCTB_CFOP = GRPIT.CLCTB_CFOP)
WHERE 
(DOC.COD_AIDF >=0) AND (DOC.PRINT_DOC = 'S')
AND COALESCE(DOC.CANC_DOC,'N') <> 'S'  AND 
((DOC.EMISS_DOC >= :Data_Inicial || ' 00:00:00' AND DOC.EMISS_DOC <= :Data_Final || ' 23:59:59' AND DOC.MOV_DOC = 'S') OR (DOC.ENTSAID_DOC >= :Data_Inicial || ' 00:00:00'  AND DOC.ENTSAID_DOC <= :Data_Final || ' 23:59:59' AND DOC.MOV_DOC = 'E'))
AND DOCIT.COD_DOCIT < 900 AND DOC.COD_MOD NOT IN ('8','57')

UNION ALL

SELECT ESTAB.FANT_ESTB || '(' || COALESCE(ESTAB.CNPJCPF_ESTB, ' ') || ')' EMPRESA,
