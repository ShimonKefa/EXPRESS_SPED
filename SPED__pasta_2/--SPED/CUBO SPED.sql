GRPIT.CST_COFINS || ' ' CST_COFINS,
COALESCE(GRPIT.BC_PIS,'S') CALC_BC_PIS,
COALESCE(GRPIT.BC_COFINS,'S') CALC_BC_COFINS FROM CUPOMIT
INNER JOIN CUPOM ON (CUPOMIT.COD_CF = CUPOM.COD_CF)
INNER JOIN ESTAB ON (ESTAB.COD_ESTAB = CUPOMIT.COD_ESTAB)
INNER JOIN CFOP ON (CFOP.COD_CFOP = 5102 AND CFOP.INT_CFOP = '00')
INNER JOIN PROD ON (PROD.COD_ESTQ = CUPOMIT.COD_ESTQ)
INNER JOIN GRPIT ON (PROD.COD_GRP = GRPIT.COD_GRP AND ESTAB.COD_ESTAB = GRPIT.COD_ESTAB AND CFOP.CLCTB_CFOP = GRPIT.CLCTB_CFOP)
WHERE CUPOMIT.DATA >= :Data_Inicial  || ' 00:00:00' AND CUPOMIT.DATA <= :Data_Final || ' 23:59:59'  
AND COALESCE(CUPOMIT.COD_ESTQ,0) <> 0  AND (CUPOMIT.CANCELADO = 'N' AND CUPOM.CANCELADO='N') 

