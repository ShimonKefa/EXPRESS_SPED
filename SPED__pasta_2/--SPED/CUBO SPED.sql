CASE WHEN COALESCE(CUPOMIT.DAITEM,0) < 0 THEN (CUPOMIT.TOTAL - COALESCE(CUPOMIT.DAITEM,0)) ELSE (CUPOMIT.TOTAL) END  VL_ITEM,
(CASE WHEN COALESCE(CUPOMIT.DAITEM,0) < 0 THEN COALESCE(CUPOMIT.DAITEM,0) * (-1)  ELSE 0 END) + (CASE WHEN COALESCE(CUPOMIT.DACUPOM,0) < 0 THEN COALESCE(CUPOMIT.DACUPOM,0) * (-1)  ELSE 0 END)  VL_DESC,
0.0 VL_FRETE,
0.0 VL_SEGURO,
(CASE WHEN COALESCE(CUPOMIT.DAITEM,0) > 0 THEN COALESCE(CUPOMIT.DAITEM,0)  ELSE 0 END) + (CASE WHEN COALESCE(CUPOMIT.DACUPOM,0) > 0 THEN COALESCE(CUPOMIT.DACUPOM,0)  ELSE 0 END)  VL_OUTDESP,
(CASE WHEN COALESCE(CUPOMIT.DAITEM,0) < 0 THEN (CUPOMIT.TOTAL - COALESCE(CUPOMIT.DAITEM,0)) ELSE (CUPOMIT.TOTAL) END) - 
((CASE WHEN COALESCE(CUPOMIT.DAITEM,0) < 0 THEN COALESCE(CUPOMIT.DAITEM,0) * (-1)  ELSE 0 END) + (CASE WHEN COALESCE(CUPOMIT.DACUPOM,0) < 0 THEN COALESCE(CUPOMIT.DACUPOM,0) * (-1)  ELSE 0 END)) +
((CASE WHEN COALESCE(CUPOMIT.DAITEM,0) > 0 THEN COALESCE(CUPOMIT.DAITEM,0)  ELSE 0 END) + (CASE WHEN COALESCE(CUPOMIT.DACUPOM,0) > 0 THEN COALESCE(CUPOMIT.DACUPOM,0)  ELSE 0 END))  VL_GERAL, 
'N' ESTQ,
CUPOMIT.ICMS ICMS,
0.0 ICMSR,
0.0 IPI,
