[SQL]
SELECT 'NOTA FISCAL :   '||DOC.NUM_DOC NOTA ,
DOCIT.NOM_DOCIT, 
PROD.TIPI_PROD NCM, 
(DOCIT.TOTAL_DOCIT+COALESCE(ICMSR_DOCIT,0)+COALESCE(SEGURO_DOCIT,0)+COALESCE(OUTDESP_DOCIT,0)+COALESCE(FRETE_DOCIT,0)) TOTAL,
 COALESCE(NCMIT.ALIQ_INSS,0) INSS
FROM DOCIT INNER JOIN DOC ON (DOC.COD_DOC = DOCIT.COD_DOC) INNER JOIN CFOP ON (DOCIT.CFOP_DOCIT = CFOP.COD_CFOP AND DOCIT.INTCFOP_DOCIT = CFOP.INT_CFOP)
INNER JOIN ESTAB ON (ESTAB.COD_ESTAB = DOC.COD_ESTAB) INNER JOIN PROD ON (PROD.COD_ESTQ = DOCIT.COD_ESTQ)
LEFT JOIN NCMIT ON (NCMIT.COD_NCM = PROD.TIPI_PROD AND ESTAB.COD_ESTAB = NCMIT.COD_ESTAB AND CFOP.CLCTB_CFOP = NCMIT.CLCTB_CFOP)
WHERE DOC.COD_AIDF >= 0 AND DOC.MOV_DOC in ("S") AND DOC.PRINT_DOC = "S" AND COALESCE(CFOP.FIN_CFOP,"N") = "S" AND COALESCE(CFOP.ESTAT_CFOP, "OUTROS") = "VENDAS" AND
COALESCE(DOC.TPAMB_DOC,"0") <> '2' AND COALESCE(DOC.STATUS_DOC,"N") <> "I" AND (COALESCE(DOC.CANC_DOC,'N') = 'N') AND
DOC.COD_AIDF >=0 AND DOCIT.CFOP_DOCIT < 7000
AND ESTAB.COD_ESTAB = :COD_ESTAB
AND COALESCE(NCMIT.SPEDINSS_TRIB,'N') = 'S' AND
(DOC.EMISS_DOC >= :Data_Inicial || ' 00:00:00' AND DOC.EMISS_DOC <= :Data_Final || ' 23:59:59' AND DOC.MOV_DOC = 'S')
ORDER BY 1
